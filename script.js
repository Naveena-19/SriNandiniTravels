els.useLocation.addEventListener('click', () => {
  if (!navigator.geolocation) {
    showToast(state.lang === 'te' ? 'ఈ ఫోన్‌లో లొకేషన్ అందుబాటులో లేదు.' : 'Location is not available on this phone.');
    return;
  }

  if (!window.isSecureContext) {
    showToast(state.lang === 'te'
      ? 'లొకేషన్ కోసం HTTPS వెబ్‌సైట్‌ను ఉపయోగించండి.'
      : 'Location needs the deployed HTTPS website.');
    return;
  }

  els.useLocation.disabled = true;
  els.useLocation.textContent = state.lang === 'te' ? 'స్థానం కనుగొంటోంది...' : 'Finding your location...';
  navigator.geolocation.getCurrentPosition(
    async (position) => {
      const { latitude, longitude } = position.coords;
      const pickupField = document.getElementById('pickup');
      pickupField.value = state.lang === 'te' ? 'చిరునామా కనుగొంటోంది...' : 'Finding your address...';

      try {
        const response = await fetch(`https://nominatim.openstreetmap.org/reverse?format=jsonv2&lat=${latitude}&lon=${longitude}&zoom=18&addressdetails=1`);
        if (!response.ok) throw new Error('Reverse geocoding failed');
        const result = await response.json();
        pickupField.value = result.display_name || `Pickup location (${latitude.toFixed(5)}, ${longitude.toFixed(5)})`;
        showToast(state.lang === 'te' ? 'పికప్ చిరునామా జోడించబడింది.' : 'Pickup address added.');
      } catch (error) {
        pickupField.value = `Pickup location (${latitude.toFixed(5)}, ${longitude.toFixed(5)})`;
        showToast(state.lang === 'te' ? 'చిరునామా దొరకలేదు. దయచేసి సరిచూడండి.' : 'Address lookup failed. Please check the pickup location.');
      } finally {
        els.useLocation.disabled = false;
        setLanguage(state.lang);
      }
    },
    (error) => {
      els.useLocation.disabled = false;
      setLanguage(state.lang);
      const message = error.code === error.PERMISSION_DENIED
        ? (state.lang === 'te' ? 'లొకేషన్ అనుమతిని ఇవ్వండి లేదా పికప్ చిరునామా నమోదు చేయండి.' : 'Allow location access, or enter the pickup address.')
        : (state.lang === 'te' ? 'లొకేషన్ పొందలేకపోయాము. పికప్ చిరునామా నమోదు చేయండి.' : 'Could not get your location. Enter the pickup address instead.');
      showToast(message);
    },
    { enableHighAccuracy: true, timeout: 10000 }
  );
});

