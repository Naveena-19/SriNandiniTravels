function setLanguage(lang) {
  state.lang = lang;
  localStorage.setItem('lang', lang);
  document.documentElement.lang = lang;

  const activeLang = translations[lang] || translations.en;
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (activeLang[key]) {
      el.textContent = activeLang[key];
    }
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (activeLang[key]) {
      el.setAttribute('placeholder', activeLang[key]);
    }
  });

  els.langOptions.forEach((option) => {
    option.classList.toggle('active', option.dataset.lang === lang);
  });

  const routeButtons = document.querySelectorAll('.route-btn');
  routeButtons.forEach((button) => {
    const current = button.getAttribute('data-i18n');
    button.textContent = activeLang[current] || button.textContent;
  });

  const carOptions = document.querySelectorAll('#carType option');
  carOptions.forEach((option) => {
    const key = option.getAttribute('data-i18n');
    if (key && activeLang[key]) {
      option.textContent = activeLang[key];
    }
  });

  const dateInput = document.getElementById('date');
  if (dateInput && !dateInput.value) {
    dateInput.min = new Date().toISOString().split('T')[0];
  }
}

function showToast(message) {
  els.toast.textContent = message;
  els.toast.classList.add('show');
  clearTimeout(showToast.timeoutId);
  showToast.timeoutId = setTimeout(() => {
    els.toast.classList.remove('show');
  }, 2200);
}

function updateURLLanguage() {
  const params = new URLSearchParams(window.location.search);
  const requested = params.get('lang');
  if (requested === 'te' || requested === 'en') {
    setLanguage(requested);
  } else {
    setLanguage(state.lang);
  }
}

function validatePhone(phone) {
  return /^[0-9]{10}$/.test(phone);
}

function generateWhatsAppMessage(formData) {
  const messageLines = [
    'New Booking Request - Sri Nandini Travels',
    `Name: ${formData.name}`,
    `Phone: ${formData.phone}`,
  ];

  if (formData.pickup) messageLines.push(`Pickup: ${formData.pickup}`);
  if (formData.destination) messageLines.push(`Drop: ${formData.destination}`);
  if (formData.date) messageLines.push(`Date: ${formData.date}`);
  if (formData.carType) messageLines.push(`Car: ${formData.carType}`);
  if (formData.pickup && formData.destination) {
    const routeParams = new URLSearchParams({
      api: '1',
      origin: formData.pickup,
      destination: formData.destination,
    });
    messageLines.push(`Google Maps route: https://www.google.com/maps/dir/?${routeParams.toString()}`);
  }

  return messageLines.join('\n');
}

function validateForm() {
  const formValues = {
    name: document.getElementById('name').value.trim(),
    phone: document.getElementById('phone').value.trim(),
    pickup: document.getElementById('pickup').value.trim(),
    destination: document.getElementById('destination').value.trim(),
    date: document.getElementById('date').value,
    carType: document.getElementById('carType').value,
  };

  if (!formValues.name || !formValues.phone) {
    showToast(state.lang === 'te' ? 'దయచేసి మీ పేరు మరియు ఫోన్ నంబర్ నమోదు చేయండి.' : 'Please enter your name and phone number.');
    return null;
  }

  if (!validatePhone(formValues.phone)) {
    showToast(state.lang === 'te' ? '10-అంకెల మొబైల్ నెంబర్ ఇవ్వండి.' : 'Please enter a valid 10-digit mobile number.');
    return null;
  }

  return formValues;
}

